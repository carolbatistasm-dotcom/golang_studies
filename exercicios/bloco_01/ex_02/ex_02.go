// fazer um programa que exiba as tabelas verdade com expressoes && e ||
package main

import "fmt"

func main() {
	fmt.Println(true && false)
	fmt.Println(true && true)
	fmt.Println(false && true)
	fmt.Println(false && false)
	fmt.Println(true || false)
	fmt.Println(true || true)
	fmt.Println(false || true)
	fmt.Println(false || false)
}
