// faça um programa que exiba a seuinte receita de bolo de chocolate

package main

import "fmt"

func main() {

	var ok string
	fmt.Println("Receita de Bolo de Chocolate:")
	fmt.Scanf("%s", &ok)
	fmt.Println("Ingredientes:")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 2 xícaras de farinha de trigo")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 1 xícara de açúcar")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 1/2 xícara de cacau em pó")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 1 colher de sopa de fermento em pó")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 1/2 xícara de óleo")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 1 xícara de leite")
	fmt.Scanf("%s", &ok)
	fmt.Println("- 3 ovos")
	fmt.Scanf("%s", &ok)
	fmt.Println("Modo de preparo:")
	fmt.Scanf("%s", &ok)
	fmt.Println("1. Preaqueça o forno a 180°C.")
	fmt.Scanf("%s", &ok)
	fmt.Println("2. Em uma tigela, misture a farinha, o açúcar, o cacau e o fermento.")
	fmt.Scanf("%s", &ok)
	fmt.Println("3. Adicione o óleo, o leite e os ovos e misture bem até obter uma massa homogênea.")
	fmt.Scanf("%s", &ok)
	fmt.Println("4. Despeje a massa em uma forma untada e enfarinhada.")
	fmt.Scanf("%s", &ok)
	fmt.Println("5. Leve ao forno por cerca de 35-40 minutos ou até que um palito saia limpo ao ser inserido no centro do bolo.")
	fmt.Scanf("%s", &ok)
	fmt.Println("6. Deixe esfriar antes de desenformar e servir.")
}
